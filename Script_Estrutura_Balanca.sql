/* 1. Geradores / Sequences */
CREATE GENERATOR GEN_TB_BALANCA_CONFIG;
CREATE GENERATOR GEN_TB_BALANCA_FILA;
CREATE GENERATOR GEN_TB_BALANCA_LOG;

/* 2. Tabela de Cadastro e Configuracao das Balancas de Rede */
CREATE TABLE TB_BALANCA_CONFIG (
  BCFG_ID INTEGER NOT NULL,
  BCFG_NOME VARCHAR(60) NOT NULL,
  BCFG_FABRICANTE VARCHAR(30) NOT NULL, /* 'Balmak', 'Toledo', 'Filizola', 'Urano', 'Elgin', 'Ramuza', 'Systel' */
  BCFG_MODELO VARCHAR(40) NOT NULL,     /* 'Balmak Athena', 'Toledo Prix 5', 'Urano TopMax', etc. */
  BCFG_IP VARCHAR(45) NOT NULL,         /* Endereco IP da balanca */
  BCFG_PORTA INTEGER DEFAULT 5000 NOT NULL,
  BCFG_SETOR INTEGER DEFAULT 0 NOT NULL, /* 0 = Todos os setores */
  BCFG_ATIVO VARCHAR(1) DEFAULT 'S' NOT NULL,
  BCFG_CAMINHO_DLL VARCHAR(255),        /* Caminho da DLL (ex: P05.dll) ou pasta de carga */
  BCFG_DT_ULTIMA_SYNC TIMESTAMP,
  BCFG_ULTIMO_LOG VARCHAR(500),
  CONSTRAINT PK_TB_BALANCA_CONFIG PRIMARY KEY (BCFG_ID)
);

/* 3. Tabela de Fila de Transmissao de Alteracoes */
CREATE TABLE TB_BALANCA_FILA (
  BFL_ID INTEGER NOT NULL,
  BFL_PRODUTO INTEGER NOT NULL,
  BFL_OPERACAO VARCHAR(1) DEFAULT 'U' NOT NULL, /* 'I'=Inclusao, 'U'=Alteracao */
  BFL_DATA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  BFL_PROCESSADO VARCHAR(1) DEFAULT 'N' NOT NULL,
  BFL_DT_PROCESSADO TIMESTAMP,
  BFL_LOG VARCHAR(500),
  CONSTRAINT PK_TB_BALANCA_FILA PRIMARY KEY (BFL_ID),
  CONSTRAINT FK_TB_BALANCA_FILA_PROD FOREIGN KEY (BFL_PRODUTO) REFERENCES TB_PRODUTO (PRD_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_TB_BALANCA_FILA_PROC ON TB_BALANCA_FILA (BFL_PROCESSADO, BFL_DATA_HORA);

/* 4. Tabela de Log e Auditoria de Cargas */
CREATE TABLE TB_BALANCA_LOG (
  BLOG_ID INTEGER NOT NULL,
  BLOG_BALANCA INTEGER NOT NULL,
  BLOG_DATA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  BLOG_ITENS_ENVIADOS INTEGER DEFAULT 0 NOT NULL,
  BLOG_STATUS VARCHAR(1) DEFAULT 'S' NOT NULL, /* 'S'=Sucesso, 'E'=Erro */
  BLOG_TEMPO_MS INTEGER DEFAULT 0,
  BLOG_MENSAGEM VARCHAR(500),
  CONSTRAINT PK_TB_BALANCA_LOG PRIMARY KEY (BLOG_ID)
);

/* 5. Trigger de Enfileiramento Automatico de Produtos Alterados */
SET TERM ^ ;
CREATE OR ALTER TRIGGER TRG_PROD_BALANCA_SYNC FOR TB_PRODUTO
ACTIVE AFTER INSERT OR UPDATE POSITION 10
AS
BEGIN
  IF (NEW.PRD_BALANCA_CODIGO IS NOT NULL AND NEW.PRD_BALANCA_CODIGO > 0) THEN
  BEGIN
    IF (INSERTING OR
        OLD.PRD_PRECO_VENDA IS DISTINCT FROM NEW.PRD_PRECO_VENDA OR
        OLD.PRD_DESCRICAO IS DISTINCT FROM NEW.PRD_DESCRICAO OR
        OLD.PRD_DESCRICAO_CURTA IS DISTINCT FROM NEW.PRD_DESCRICAO_CURTA OR
        OLD.PRD_BALANCA_VALIDADE IS DISTINCT FROM NEW.PRD_BALANCA_VALIDADE OR
        OLD.PRD_BALANCA_TIPO IS DISTINCT FROM NEW.PRD_BALANCA_TIPO OR
        OLD.PRD_BALANCA_TECLA IS DISTINCT FROM NEW.PRD_BALANCA_TECLA OR
        OLD.PRD_SETOR IS DISTINCT FROM NEW.PRD_SETOR OR
        OLD.PRD_STATUS IS DISTINCT FROM NEW.PRD_STATUS) THEN
    BEGIN
      INSERT INTO TB_BALANCA_FILA (
        BFL_ID,
        BFL_PRODUTO,
        BFL_OPERACAO,
        BFL_DATA_HORA,
        BFL_PROCESSADO,
        BFL_LOG
      ) VALUES (
        GEN_ID(GEN_TB_BALANCA_FILA, 1),
        NEW.PRD_ID,
        'U',
        CURRENT_TIMESTAMP,
        'N',
        'TRIGGER AUTOMATICA DE ALTERACAO'
      );
    END
  END
END ^
SET TERM ; ^

COMMIT;